/* @ts-check */
import esbuild from 'esbuild'
import path from 'node:path'
import process from 'process'
import { builtinModules } from 'node:module'
import esbuildSvelte from 'esbuild-svelte' // 可能会报错，需要将`??`改成一般的三元运算符
import { sveltePreprocess } from 'svelte-preprocess'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

const prod = process.argv[2] === 'production'

// グラフ計算用のワーカーを別にバンドルし、文字列としてメインのバンドルに埋め込む
const inlineGraphWorkerPlugin = {
  name: 'inline-graph-worker',
  setup(build) {
    build.onResolve({ filter: /^inline-graph-worker$/ }, (args) => ({
      path: args.path,
      namespace: 'inline-graph-worker',
    }))
    build.onLoad({ filter: /.*/, namespace: 'inline-graph-worker' }, async () => {
      const worker = await esbuild.build({
        entryPoints: ['src/workers/graph.worker.ts'],
        bundle: true,
        format: 'iife',
        target: 'es2018',
        minify: prod,
        treeShaking: true,
        metafile: true,
        write: false,
      })
      return {
        contents: `export default ${JSON.stringify(worker.outputFiles[0].text)}`,
        loader: 'js',
        watchFiles: Object.keys(worker.metafile.inputs).map((file) =>
          path.resolve(file)
        ),
      }
    })
  },
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  plugins: [
    inlineGraphWorkerPlugin,
    esbuildSvelte({
      compilerOptions: {
        css: 'injected',
        warningFilter: (warning) => !warning.code.startsWith('a11y'), // a11y-から始まる警告をすべて無視
      },
      preprocess: sveltePreprocess(),
    }),
  ],
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    'node:*',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2018',
  logLevel: 'info',
  minify: prod,
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
})

if (prod) {
  await context.rebuild()
  process.exit(0)
} else {
  await context.watch()
}
